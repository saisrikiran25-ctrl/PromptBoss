async function callGemini(systemPrompt, userPrompt, modelName) {
  const store = useAppStore.getState();
  const apiKey = store.geminiKey;
  
  if (!apiKey) {
    throw Object.assign(new Error('NO_KEY'), {
      userMessage: 'No Gemini API key configured. Please configure your environment variables (VITE_GEMINI_KEY).',
    });
  }

  const requestedModel = modelName.replace('google/', '');

  // Ordered list of candidate models to try. Starts with requested model, then falls back to others.
  const candidates = [
    requestedModel,
    'gemini-2.5-pro',
    'gemini-2.5-flash',
    'gemini-2.0-flash',
    'gemini-1.5-pro',
    'gemini-1.5-flash'
  ];

  // Remove duplicates while keeping order
  const uniqueCandidates = [...new Set(candidates)];
  let lastError;

  for (const model of uniqueCandidates) {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;
    store.setKeyStatus('active');

    try {
      const res = await fetch(url, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          contents: [
            {
              role: 'user',
              parts: [{ text: userPrompt }]
            }
          ],
          systemInstruction: {
            parts: [{ text: systemPrompt }]
          },
          generationConfig: {
            temperature: 0.3,
            responseMimeType: 'application/json'
          }
        }),
        signal: AbortSignal.timeout(60000),
      });

      if (!res.ok) {
        const errText = await res.text().catch(() => '');
        let errMsg = `HTTP ${res.status}`;
        try {
          const parsed = JSON.parse(errText);
          errMsg = parsed?.error?.message || errMsg;
        } catch {}
        throw new Error(errMsg);
      }

      const data = await res.json();
      const content = data?.candidates?.[0]?.content?.parts?.[0]?.text;
      if (!content) {
        throw new Error('Empty response from Gemini API');
      }

      // If we succeeded with a model other than the requested one, update store and localStorage
      if (model !== requestedModel) {
        console.warn(`Requested model '${requestedModel}' failed, successfully fell back to '${model}'.`);
        store.setSelectedModel(model);
      }

      store.setKeyStatus('healthy');
      return content;
    } catch (err) {
      console.warn(`Gemini call failed for model '${model}': ${err.message}. Trying next candidate...`);
      lastError = err;
    }
  }

  // If we reach here, all candidates failed
  store.setKeyStatus('error');
  throw Object.assign(new Error(`All Gemini models failed. Last error: ${lastError?.message}`), {
    userMessage: `Gemini API call failed for all models. Last error: ${lastError?.message}`
  });
}

