export async function testApiKey(apiKey) {
  try {
    const res = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${apiKey}`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        contents: [{ role: 'user', parts: [{ text: 'ping' }] }],
        generationConfig: { maxOutputTokens: 5 }
      }),
      signal: AbortSignal.timeout(10000),
    });

    if (res.status === 400) {
      const errText = await res.text().catch(() => '');
      if (errText.includes('API key not valid')) {
        return { valid: false, reason: 'Invalid API key' };
      }
    }
    if (res.status === 403) return { valid: false, reason: 'Permission denied / Invalid API key' };
    if (res.status === 429) return { valid: true, reason: 'Key valid but rate limited' };
    if (!res.ok) return { valid: false, reason: `HTTP ${res.status}` };
    return { valid: true, reason: 'Healthy' };
  } catch (e) {
    return { valid: false, reason: e.message };
  }
}
