export async function improvePrompt(
  { prompt, taskType, targetModel, outputStyle, tone, mode = 'improve' },
  { onChunk } = {}
) {
  const { selectedModel } = useAppStore.getState();

  const userMessage = `Please improve this prompt:

"${prompt}"

Configuration:
- Task Type: ${taskType || 'auto-detect'}
- Target Model: ${targetModel || 'generic'}
- Output Style: ${outputStyle || 'structured'}
- Tone: ${tone || 'professional'}
- Mode: ${mode}`;

  try {
    const content = await callGemini(IMPROVE_SYSTEM_PROMPT, userMessage, selectedModel);
    
    useAppStore.getState().setFallbackActive(false);
    useAppStore.getState().setFallbackNote('');
    
    if (onChunk) {
      await simulateStream(content, onChunk);
      return content;
    }
    return {
      choices: [
        {
          message: {
            content: content
          }
        }
      ]
    };
  } catch (err) {
    useAppStore.getState().setFallbackActive(true);
    useAppStore.getState().setFallbackNote("Generated by deterministic fallback engine. No AI API was used. Results are rule-based.");
    
    const fallbackResult = runFallbackEngine(prompt, taskType, targetModel, 'improve');
    const improveResponse = {
      quick_version: fallbackResult.quickVersion,
      advanced_version: fallbackResult.advancedVersion,
      diagnosis: fallbackResult.diagnosis.weaknesses.map(w => ({
        category: w.category,
        severity: w.severity,
        title: w.title,
        description: w.description
      })),
      alternatives: fallbackResult.alternatives
    };
    const jsonString = JSON.stringify(improveResponse, null, 2);

    if (onChunk) {
      await simulateStream(jsonString, onChunk);
      return jsonString;
    }
    return {
      choices: [
        {
          message: {
            content: jsonString
          }
        }
      ]
    };
  }
}

